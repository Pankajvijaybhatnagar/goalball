    <h1>How to Play Goalball</h1>
    <img width='75%' src="goalball-rules.jpg" alt="Goalball in action">

    <div class="section">
        <h2>Goalball</h2>
        <p>Goalball is a unique team sport designed specifically for athletes who are blind or visually impaired. It
            combines strategy, teamwork, and quick reflexes, and is played on a rectangular court with tactile markings.
        </p>
    </div>

    <div class="section">
        <h2>Objective</h2>
        <p>The goal of the game is simple: score goals by rolling a ball into the opponent’s net, while defending your
            own goal from incoming shots. The ball contains bells so players can hear its movement.</p>
    </div>

    <div class="section">
        <h2>Basic Setup</h2>
        <ul>
            <li>🟦 <strong>Teams:</strong> Two teams of three players each.</li>
            <li>🟧 <strong>Court:</strong> An 18m x 9m indoor court, split into two halves.</li>
            <li>🥅 <strong>Goals:</strong> Stretch the full width (9m) at each end.</li>
            <li>🧤 <strong>Equipment:</strong> A special blue rubber ball with bells, and eyeshades (worn by all players
                for equal visual conditions).</li>
            <li>🛡️ <strong>Orientation:</strong> Tactile lines and string under the tape help players navigate the
                court by touch.</li>
        </ul>
    </div>

    <div class="section">
        <h2>Gameplay</h2>
        <ul>
            <li><strong>Start:</strong> A coin toss decides which team starts with the ball or picks their side.</li>
            <li><strong>Throwing:</strong> Players throw (roll) the ball along the floor, trying to score by getting it
                into the opponent’s goal.</li>
            <li><strong>Defending:</strong> Defenders dive or slide to block the ball using their bodies. All defense is
                done by ear, listening to the bell inside the ball.</li>
            <li><strong>Timing:</strong> Teams must return the ball within 10 seconds of gaining possession.</li>
            <li><strong>Communication:</strong> Since the game depends on sound, silence is critical. Spectators must
                remain quiet, and players must avoid unnecessary noise during play.</li>
        </ul>
    </div>

    <div class="section">
        <h2>Scoring</h2>
        <ul>
            <li>A goal is scored when the ball completely crosses the opponent’s goal line.</li>
            <li>Games are 24 minutes long (two 12-minute halves), with a 5-minute halftime.</li>
            <li>The game ends early if a team leads by 10 goals.</li>
        </ul>
    </div>

    <div class="section">
        <h2>Rules and Penalties</h2>
        <p>All players wear eyeshades to ensure no one can see, regardless of their level of vision.</p>
        <p><strong>Infractions include:</strong></p>
        <ul>
            <li>High ball (ball doesn't touch the floor early enough)</li>
            <li>Short ball, long ball</li>
            <li>Noise or illegal defense</li>
        </ul>
        <p>These are penalized with a <strong>penalty throw</strong> (a one-on-one shot).</p>
        <p><strong>Teams are allowed:</strong></p>
        <ul>
            <li>4 time-outs per game</li>
            <li>4 player substitutions</li>
            <li>1 time-out and 1 substitution in overtime</li>
        </ul>
    </div>

    <div class="section">
        <h2>Winning the Game</h2>
        <p>The team with more goals at the end of regulation wins. If tied, overtime and then extra throws or sudden
            death decide the winner.</p>
    </div>

    <div class="section">
        <h2>Who Can Play?</h2>
        <p>Though created for blind and visually impaired players, sighted players can also play recreationally—wearing
            the same eyeshades for fairness. It’s a popular sport at the Paralympic Games, known for its intensity and
            fast pace.</p>
    </div>
</div>













