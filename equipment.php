        <div class="section">
            <h2>Essential Equipment</h2>
            <ul>
                <li>🏐 <strong>Goalball:</strong> A heavy rubber ball weighing approximately 1.25 kg, with holes and bells inside to help players locate it by sound.</li>
                <li>🧤 <strong>Eyeshades:</strong> Worn by all players, ensuring equal visual impairment regardless of vision levels. These must block all light completely.</li>
                <li>🛡️ <strong>Protective Gear:</strong> Players wear knee pads, elbow pads, hip pads, and sometimes chest protection to prevent injury while diving.</li>
                <li>👕 <strong>Uniforms:</strong> Matching team uniforms with large, clear numbers on front and back for identification. No reflective material is allowed.</li>
                <li>🩹 <strong>Eye Patches:</strong> Soft patches are worn under the eyeshades to prevent any light perception.</li>
            </ul>
        </div>

        <div class="section">
            <h2>Court Setup</h2>
            <ul>
                <li>📏 <strong>Dimensions:</strong> The court is 18 meters long and 9 meters wide, the same size as a volleyball court.</li>
                <li>🥅 <strong>Goals:</strong> Stretch across the entire width (9 meters) of each end of the court and are 1.3 meters high.</li>
                <li>📌 <strong>Tactile Lines:</strong> Raised tape with string underneath is used to mark areas like goal lines, team areas, and orientation lines. Players feel these with their hands or feet.</li>
                <li>🟧 <strong>Zones:</strong>
                    <ul>
                        <li><strong>Team Area (3m):</strong> Closest to the goal, where players defend and throw from.</li>
                        <li><strong>Landing Area (3m):</strong> The ball must land here when thrown.</li>
                        <li><strong>Neutral Area (center 6m):</strong> Ball must pass through to be legal.</li>
                    </ul>
                </li>
                <li>🔇 <strong>Quiet Environment:</strong> The entire facility must be silent during play so athletes can hear the ball and team communication.</li>
            </ul>
        </div>

        <div class="section">
            <h2>Maintenance and Setup Tips</h2>
            <p>Ensure the court surface is clean and free of debris. Tactile lines should be securely taped with consistent height. Balls must be tested for proper bell sound. Eyeshades should be checked for integrity before every session.</p>
        </div>

