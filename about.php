        <h3>The Journey (History)</h3>
        <h5>Origins (1946)</h5>
        <p>Goalball was invented in 1946 by Austrian Hanz Lorenzen and German Sepp Reindle as
            a rehabilitation sport for visually impaired World War II veterans. The game was designed
            to improve orientation, concentration, and physical coordination using sound and spatial
            awareness
        </p>
        <br>
        <h5>Global Recognition</h5>
        <p>In 1976, Goalball made its debut as a competitive sport in the Paralympic Games in Toronto,
            Canada. Since then, it has been a core part of every Summer Paralympics, governed
            internationally by the International Blind Sports Federation (IBSA). The sport has seen
            innovations in rules, coaching, and global participation over the decades.
        </p>
