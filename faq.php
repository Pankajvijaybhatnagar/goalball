        <div class="faq-item">
            <div class="faq-question">1. What is Goalball?</div>
            <div class="faq-answer">Goalball is a team sport created for athletes who are blind or visually impaired. Players aim to roll a ball with bells into the opponent’s goal while defending their own.</div>
        </div>

        <div class="faq-item">
            <div class="faq-question">2. How many players are on each team?</div>
            <div class="faq-answer">Each team has 3 players on the court at a time, with up to 3 substitutes available during official matches.</div>
        </div>

        <div class="faq-item">
            <div class="faq-question">3. Do sighted players wear eyeshades too?</div>
            <div class="faq-answer">Yes, all players wear eyeshades to ensure total equality in vision, regardless of visual ability.</div>
        </div>

        <div class="faq-item">
            <div class="faq-question">4. How do players know where they are on the court?</div>
            <div class="faq-answer">The court has tactile lines made from tape over string, allowing players to feel their position and orientation during the game.</div>
        </div>

        <div class="faq-item">
            <div class="faq-question">5. What is the goalball made of?</div>
            <div class="faq-answer">The goalball is made of hard rubber, weighs 1.25 kg, has holes in it, and contains bells so players can track it by sound.</div>
        </div>

        <div class="faq-item">
            <div class="faq-question">6. How long is a game?</div>
            <div class="faq-answer">Games are 24 minutes long, divided into two 12-minute halves, with a 5-minute halftime break.</div>
        </div>

        <div class="faq-item">
            <div class="faq-question">7. How do teams score?</div>
            <div class="faq-answer">A goal is scored when the ball completely crosses the opponent’s goal line.</div>
        </div>

        <div class="faq-item">
            <div class="faq-question">8. What are some common penalties?</div>
            <div class="faq-answer">Common penalties include high ball, short ball, noise, illegal defense, and 10-second violations. These result in one-on-one penalty throws.</div>
        </div>

        <div class="faq-item">
            <div class="faq-question">9. Where is Goalball played competitively?</div>
            <div class="faq-answer">Goalball is played internationally, including in the Paralympic Games, IBSA World Championships, and national tournaments worldwide.</div>
        </div>

        <div class="faq-item">
            <div class="faq-question">10. Can beginners or kids play Goalball?</div>
            <div class="faq-answer">Absolutely! There are recreational and youth programs that teach the basics of Goalball in a safe and fun environment.</div>
        </div>

        <div class="faq-item">
            <div class="faq-question">11. Is Goalball only for the blind?</div>
            <div class="faq-answer">It is designed for blind and visually impaired players, but anyone can play recreationally by wearing eyeshades for fairness.</div>
        </div>

        <div class="faq-item">
            <div class="faq-question">12. What skills are important in Goalball?</div>
            <div class="faq-answer">Key skills include sound localization, throwing strength, teamwork, diving technique, and court awareness.</div>
